const { chromium } = require('playwright');
const { start, G } = require('./server');
const ok = (cond, msg) => { console.log((cond ? 'ok - ' : 'FALHA - ') + msg); if (!cond) process.exitCode = 1; };
(async () => {
  G.context.setup();
  const TOKEN = '8123456789:AAH' + 'k'.repeat(32);
  let updates = [];
  G.setTg((method, body) => {
    if (method === 'getMe') return { ok: true, result: { username: 'prumo_teste_bot', first_name: 'Prumo' } };
    if (method === 'getUpdates') return { ok: true, result: updates.filter((u) => u.update_id >= (body.offset || 0)) };
    return { ok: true, result: { message_id: 1 } };
  });
  const srv = await start(8765);
  const browser = await chromium.launch();
  const errs = [];
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, colorScheme: 'dark' });
  page.on('pageerror', (e) => errs.push(e.message));
  await page.goto('http://localhost:8765/'); await page.waitForSelector('.page');
  await page.evaluate(() => { location.hash = '#/cfg'; }); await page.waitForTimeout(400);
  ok(await page.isVisible('a[href="#/cfg/telegram"]') && !(await page.isVisible('a[href="#/cfg/whatsapp"]')), 'Configurações mostra Telegram no lugar do WhatsApp');
  await page.click('a[href="#/cfg/telegram"]'); await page.waitForSelector('#tg-tk');
  await page.screenshot({ path: 'shots/tg_m_inicio.png', fullPage: true });
  await page.fill('#tg-tk', TOKEN); await page.click('[data-act="tg.saveCfg"]'); await page.waitForTimeout(1000);
  ok(await page.isVisible('text=@prumo_teste_bot'), 'bot aparece depois de salvar o token');
  await page.evaluate(() => { window.open = (u) => { window.__opened = u; }; });
  await page.click('[data-act="tg.link"]'); await page.waitForTimeout(800);
  const url = await page.evaluate(() => window.__opened);
  ok(/t\.me\/prumo_teste_bot\?start=/.test(url), 'botão abre o link do bot');
  updates.push({ update_id: 1, message: { from: { id: 42, first_name: 'Gois' }, chat: { id: 42, type: 'private' }, text: '/start ' + url.split('start=')[1] } });
  await page.click('[data-act="tg.poll"].btn'); await page.waitForTimeout(1200);
  ok(await page.isVisible('text=Conectado como Gois'), '"Verificar" conecta e mostra o nome');
  await page.click('[data-act="tg.test"]'); await page.waitForTimeout(1200);
  ok(G.tgCalls.some((x) => x.method === 'sendMessage' && /Teste de envio/.test(x.body.text)), 'teste enviado pela API do Telegram');
  await page.click('.toggle:has(input[data-on-change="tg.auto"])'); await page.waitForSelector('.dialog'); await page.click('.dialog .btn-primary'); await page.waitForTimeout(900);
  await page.screenshot({ path: 'shots/tg_m_conectado.png', fullPage: true });
  const desk = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
  desk.on('pageerror', (e) => errs.push(e.message));
  await desk.goto('http://localhost:8765/'); await desk.waitForSelector('.page');
  await desk.evaluate(() => { location.hash = '#/cfg/telegram'; }); await desk.waitForTimeout(1200);
  await desk.screenshot({ path: 'shots/tg_d.png' });
  console.log(errs.length ? 'ERROS JS: ' + errs.join(' | ') : 'sem erros de JS');
  await browser.close(); srv.close();
})().catch((e) => { console.error(e); process.exit(1); });
